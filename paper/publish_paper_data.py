#!/usr/bin/env python3
"""Commit the day's paper files onto the paper-data branch. No broker credentials."""
import argparse, os, shutil, subprocess, sys
from pathlib import Path

DAY_FILES = (
    "state.json",
    "trades.csv",
    "ledger.csv",
    "rule_stats.json",
    "changes.csv",
    "journal.xlsx",
    "report.md",
)
ROOT_FILES = ("ledger.csv", "rule_stats.json", "changes.csv", "rules_current.json")


def _run(cmd, cwd, env=None):
    print("+", " ".join(cmd))
    subprocess.check_call(cmd, cwd=cwd, env=env)


def publish(repo, data_root, session_date):
    repo = Path(repo).resolve()
    data_root = Path(data_root).resolve()
    status = data_root / "RUN_STATUS"
    if status.exists() and status.read_text().strip() == "skipped":
        print("session skipped; not publishing")
        return 0
    day = data_root / session_date
    if not day.is_dir():
        print(f"no day folder {day}; not publishing")
        return 0

    wd = Path("/tmp/paper-data-worktree")
    if wd.exists():
        subprocess.run(["git", "worktree", "remove", "--force", str(wd)], cwd=repo, check=False)
        shutil.rmtree(wd, ignore_errors=True)
    fetched = subprocess.run(["git", "fetch", "origin", "paper-data"], cwd=repo)
    have_remote = subprocess.run(
        ["git", "rev-parse", "--verify", "origin/paper-data"], cwd=repo
    ).returncode == 0
    if have_remote and fetched.returncode == 0:
        _run(["git", "worktree", "add", "--force", str(wd), "origin/paper-data"], repo)
    else:
        _run(["git", "worktree", "add", "--detach", "--force", str(wd), "HEAD"], repo)
        _run(["git", "checkout", "--orphan", "paper-data"], wd)
        subprocess.run(["git", "rm", "-rf", "--cached", "--ignore-unmatch", "."], cwd=wd, check=False)
        for child in wd.iterdir():
            if child.name == ".git":
                continue
            if child.is_dir():
                shutil.rmtree(child)
            else:
                child.unlink()

    dest_root = wd / "paper-data"
    dest_day = dest_root / session_date
    dest_day.mkdir(parents=True, exist_ok=True)
    for name in DAY_FILES:
        src = day / name
        if src.exists():
            shutil.copy(src, dest_day / name)
    for name in ROOT_FILES:
        src = data_root / name
        if src.exists():
            shutil.copy(src, dest_root / name)
    readme = dest_root / "README.md"
    if not readme.exists():
        readme.write_text(
            "# paper-data\n\n"
            "Generated by the paper-only engine. No broker, no orders.\n"
            "Each session lives in `YYYY-MM-DD/`. Root CSV/JSON files are the running books.\n"
        )

    env = os.environ.copy()
    env["GIT_AUTHOR_NAME"] = "github-actions[bot]"
    env["GIT_AUTHOR_EMAIL"] = "41898282+github-actions[bot]@users.noreply.github.com"
    env["GIT_COMMITTER_NAME"] = env["GIT_AUTHOR_NAME"]
    env["GIT_COMMITTER_EMAIL"] = env["GIT_AUTHOR_EMAIL"]
    _run(["git", "add", "paper-data"], wd, env)
    dirty = subprocess.run(["git", "status", "--porcelain"], cwd=wd, capture_output=True, text=True, check=True)
    if not dirty.stdout.strip():
        print("paper-data already up to date")
    else:
        _run(["git", "commit", "-m", f"paper-data: {session_date}"], wd, env)
        _run(["git", "push", "origin", "HEAD:paper-data"], wd, env)
    subprocess.run(["git", "worktree", "remove", "--force", str(wd)], cwd=repo, check=False)
    return 0


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--data-root", required=True)
    ap.add_argument("--date", help="YYYY-MM-DD; default reads SESSION_DATE in the data root")
    args = ap.parse_args(argv)
    session = args.date
    if not session:
        session = (Path(args.data_root) / "SESSION_DATE").read_text().strip()
    return publish(args.repo, args.data_root, session)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
